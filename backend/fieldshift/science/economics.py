"""Country-specific economics: the field's country, its currency and the prices and costs used for margins.

ADR-027. Every money value IA computes (gross margins, plan impact, solar vs. diesel water cost) uses
numbers for the country the field is in, from official open data generated by scripts/build_country_data.py:

* country: offline 5 arc-min grid rasterised from Natural Earth admin-0 (no network at run time);
* crop prices: FAOSTAT producer prices (USD/t, mean of the latest 3 years ≥ 2017) for the country, else the
  median of its UN M49 sub-region, else the world median, else the crop table's reference price scaled by the
  country's farm-price index (FAOSTAT prices relative to the world median);
* production costs: the crop table's reference budget scaled by the country's own FAOSTAT yield level
  (input intensity) and World Bank price level (PPP / exchange rate) for the non-traded share;
* currency: CLDR territory currency, World Bank official exchange rate (period average);
* diesel: World Bank pump price for diesel, brought forward with the Brent crude cost per litre;
* solar pump capex: world system price, installation share scaled by the country's price level;
* fertiliser N: World Bank Pink Sheet urea (world market, no country series) with a farm-gate mark-up.

Calculations stay in USD (scores and thresholds are calibrated in USD); every response also carries the
local-currency values and an `economics` block saying which country, source, year and fallback level was used.
"""

from __future__ import annotations

import json
import math
import statistics
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any

import numpy as np
import yaml

CONFIG = Path(__file__).resolve().parents[1] / "config"
GRID = CONFIG / "country_grid_5mn.npz"
DATA = CONFIG / "country_data.json"
RES = 1.0 / 12.0

SCOPE_ORDER = ("country", "region", "world", "reference_scaled", "reference")


@lru_cache
def _grid() -> tuple[np.ndarray, list[str]] | None:
    if not GRID.exists():
        return None
    z = np.load(GRID, allow_pickle=False)
    return z["country"], [str(s) for s in z["codes"]]


@lru_cache
def data() -> dict[str, Any]:
    if not DATA.exists():
        return {"countries": {}, "world_prices": {}, "region_prices": {}, "sources": {}}
    out: dict[str, Any] = json.loads(DATA.read_text())
    return out


@lru_cache
def params() -> dict[str, Any]:
    with open(CONFIG / "economics.yaml") as f:
        out: dict[str, Any] = yaml.safe_load(f) or {}
    return out


def country_of(lat: float, lon: float) -> str | None:
    """ISO 3166 alpha-3 code of the country at a location (offline), or None at sea / outside the grid.

    Coastal points on a water cell take the nearest land cell within ~15 km (2 cells)."""
    g = _grid()
    if g is None or not (math.isfinite(lat) and math.isfinite(lon)):
        return None
    grid, codes = g
    h, w = grid.shape
    row = int(np.clip((90.0 - lat) // RES, 0, h - 1))
    col = int(np.clip((lon + 180.0) // RES, 0, w - 1))
    v = int(grid[row, col])
    if v:
        return codes[v - 1]
    for k in (1, 2):
        best: tuple[int, int] | None = None
        for dr in range(-k, k + 1):
            for dc in range(-k, k + 1):
                r, c = row + dr, (col + dc) % w
                if 0 <= r < h and grid[r, c]:
                    d = dr * dr + dc * dc
                    if best is None or d < best[0]:
                        best = (d, int(grid[r, c]))
        if best:
            return codes[best[1] - 1]
    return None


def _crop(cid: str) -> dict[str, Any]:
    from .cropmodel import crops

    return crops().get(cid, {})


@lru_cache
def _region_medians(key: str) -> dict[str, float]:
    """Median of a per-country scalar (e.g. price_level) by UN M49 sub-region."""
    by: dict[str, list[float]] = {}
    for e in data()["countries"].values():
        v = (e.get(key) or {}).get("value")
        if v is not None and e.get("sub_region"):
            by.setdefault(e["sub_region"], []).append(float(v))
    return {k: statistics.median(v) for k, v in by.items()}


@lru_cache
def _world_median(key: str) -> float | None:
    vals = [
        float(e[key]["value"])
        for e in data()["countries"].values()
        if (e.get(key) or {}).get("value") is not None
    ]
    return statistics.median(vals) if vals else None


@dataclass
class Econ:
    """Economic context of one country (or the reference fallback when the country is unknown)."""

    iso3: str | None
    entry: dict[str, Any] = field(default_factory=dict)

    # ------------------------------------------------------------------ identity and currency
    @property
    def fallback(self) -> bool:
        return self.iso3 is None or not self.entry

    @property
    def name(self) -> str | None:
        return self.entry.get("name") if self.entry else None

    @property
    def sub_region(self) -> str | None:
        return self.entry.get("sub_region") if self.entry else None

    @property
    def currency(self) -> dict[str, Any]:
        cur = (self.entry or {}).get("currency") or {}
        if cur.get("per_usd"):
            return cur
        # no exchange rate for the country's currency: show USD and say why
        return {
            "code": "USD",
            "symbol": "$",
            "per_usd": 1.0,
            "year": None,
            "source": (
                f"no official exchange rate for {cur['code']} in World Bank WDI; amounts shown in USD"
                if cur.get("code")
                else "country unknown; amounts shown in USD"
            ),
        }

    def local(self, usd: float) -> float:
        return float(usd) * float(self.currency["per_usd"])

    def _scalar(self, key: str) -> tuple[float | None, str, int | None]:
        """Country value of a WDI-derived scalar, else sub-region median, else world median."""
        e = (self.entry or {}).get(key) or {}
        if e.get("value") is not None:
            return float(e["value"]), "country", e.get("year")
        sub = self.sub_region
        if sub and sub in _region_medians(key):
            return _region_medians(key)[sub], "region", None
        return _world_median(key), "world", None

    # ------------------------------------------------------------------ crop prices and costs
    def price(self, cid: str) -> dict[str, Any]:
        """Producer price of a crop in USD per tonne of marketed product, with provenance."""
        d = data()
        items = params().get("faostat_items") or {}
        item = items.get(cid) or {}
        src = "FAOSTAT Producer Prices (PP)"
        p = ((self.entry or {}).get("prices") or {}).get(cid)
        if p:
            return {
                "usd_t": float(p["usd_t"]),
                "scope": "country",
                "years": p.get("years"),
                "source": src + (f", proxy item {item.get('name')}" if item.get("proxy") else ""),
            }
        sub = self.sub_region
        rp = (d.get("region_prices") or {}).get(sub or "", {}).get(cid)
        if rp:
            return {
                "usd_t": float(rp),
                "scope": "region",
                "region": sub,
                "years": None,
                "source": src + f", median of {sub}",
            }
        wp = (d.get("world_prices") or {}).get(cid)
        if wp:
            return {"usd_t": float(wp), "scope": "world", "years": None, "source": src + ", world median"}
        ref = float(_crop(cid).get("price_usd_t", 0) or 0)
        idx = ((self.entry or {}).get("farm_price_index") or {}).get("value")
        if idx and ref:
            us = float(d.get("us_farm_price_index") or 1.0)
            return {
                "usd_t": ref * float(idx) / us,
                "scope": "reference_scaled",
                "years": None,
                "source": "crop-table reference price scaled by the country's FAOSTAT farm-price index "
                f"({float(idx):.2f} vs. {us:.2f} for the reference)",
            }
        return {
            "usd_t": ref,
            "scope": "reference",
            "years": None,
            "source": "crop-table reference price (no country data)",
        }

    def price_usd_t(self, cid: str) -> float:
        return float(self.price(cid)["usd_t"])

    def cost(self, cid: str) -> dict[str, Any]:
        """Production cost per hectare (USD), modelled from the country's yield level and price level."""
        c = _crop(cid)
        ref = float(c.get("cost_usd_ha", 0) or 0)
        if self.fallback:
            return {
                "usd_ha": ref,
                "scope": "reference",
                "source": "crop-table reference budget (country unknown)",
            }
        cfg = params().get("costs") or {}
        ts = float(cfg.get("tradable_share", 0.6))
        lo, hi = (float(x) for x in cfg.get("intensity_clip", [0.1, 1.3]))
        typ = float(c.get("typical_yield_t_ha", 0) or 0)
        y = ((self.entry or {}).get("yields") or {}).get(cid)
        if y and typ > 0:
            intensity, i_scope = float(y["t_ha"]) / typ, "country"
        elif (self.entry or {}).get("yield_index"):
            intensity, i_scope = float(self.entry["yield_index"]["value"]), "country (all crops)"
        else:
            intensity, i_scope = 1.0, "reference"
        intensity = float(np.clip(intensity, lo, hi))
        plr, p_scope, p_year = self._scalar("price_level")
        plr = float(plr) if plr is not None else 1.0
        usd = ref * intensity * (ts + (1 - ts) * plr)
        return {
            "usd_ha": usd,
            "scope": "country" if i_scope.startswith("country") and p_scope == "country" else "modelled",
            "intensity": round(intensity, 3),
            "intensity_scope": i_scope,
            "price_level": round(plr, 3),
            "price_level_scope": p_scope,
            "price_level_year": p_year,
            "source": "reference budget × FAOSTAT national yield level × World Bank price level (PA.NUS.PPP ÷ PA.NUS.FCRF)",
        }

    def cost_usd_ha(self, cid: str) -> float:
        return float(self.cost(cid)["usd_ha"])

    def margin_usd_ha(self, cid: str, yield_t_ha: float) -> float:
        return yield_t_ha * self.price_usd_t(cid) - self.cost_usd_ha(cid)

    # ------------------------------------------------------------------ inputs
    def n_price(self) -> dict[str, Any]:
        n = (data().get("nitrogen") or params().get("nitrogen")) or {}
        urea = float(n.get("urea_usd_t", 338))
        usd_kg = urea / 1000.0 / float(n.get("n_share", 0.46)) * float(n.get("farm_gate_markup", 1.6))
        return {
            "usd_kg": round(usd_kg, 3),
            "scope": "world",
            "year": n.get("urea_year"),
            "source": "World Bank Pink Sheet urea (world market) ÷ 46 % N × farm-gate mark-up; no open country series",
        }

    def n_price_usd_kg(self) -> float:
        return float(self.n_price()["usd_kg"])

    def diesel(self) -> dict[str, Any]:
        e = (self.entry or {}).get("diesel")
        if e:
            return {
                "usd_l": float(e["usd_l"]),
                "scope": "country",
                "year": e.get("year"),
                "reported_year": e.get("reported_year"),
                "source": "World Bank WDI EP.PMP.DESL.CD (pump price for diesel), "
                f"{e.get('reported_year')} value + change in Brent crude cost per litre to {e.get('year')}",
            }
        vals = [
            float(x["diesel"]["usd_l"])
            for x in data()["countries"].values()
            if x.get("diesel") and x.get("sub_region") and x.get("sub_region") == self.sub_region
        ]
        if vals:
            return {
                "usd_l": statistics.median(vals),
                "scope": "region",
                "year": None,
                "source": f"median pump price of {self.sub_region} (World Bank WDI EP.PMP.DESL.CD)",
            }
        dflt = float((params().get("diesel") or {}).get("world_default_usd_l", 1.10))
        return {
            "usd_l": dflt,
            "scope": "world",
            "year": 2024,
            "source": "world average retail diesel (no country data)",
        }

    def solar_capex(self) -> dict[str, Any]:
        s = params().get("solar") or {}
        base = float(s.get("capex_world_usd_kwp", 1000))
        hw = float(s.get("hardware_share", 0.65))
        plr, scope, year = self._scalar("price_level")
        wmed = float(data().get("world_price_level_median") or _world_median("price_level") or 1.0)
        if plr is None or self.fallback:
            return {
                "usd_kwp": base,
                "scope": "world",
                "source": "world small-system price (IRENA 2016; FAO & GIZ 2018)",
            }
        f = hw + (1 - hw) * float(plr) / wmed
        return {
            "usd_kwp": round(base * f),
            "scope": "country" if scope == "country" else scope,
            "price_level": round(float(plr), 3),
            "year": year,
            "source": "world small-system price (IRENA 2016; FAO & GIZ 2018), installation share scaled by "
            "the World Bank price level (PA.NUS.PPP ÷ PA.NUS.FCRF) relative to the world median",
        }

    # ------------------------------------------------------------------ API
    def money(self, usd: float | None) -> dict[str, Any] | None:
        """{usd, local, currency} for one amount."""
        if usd is None:
            return None
        return {
            "usd": round(float(usd), 2),
            "local": round(self.local(usd), 2),
            "currency": self.currency["code"],
        }

    def provenance(self, crop_ids: list[str] | None = None) -> dict[str, Any]:
        """The `economics` block of an API response."""
        cur = self.currency
        out: dict[str, Any] = {
            "country": None
            if self.fallback
            else {
                "iso3": self.iso3,
                "iso2": self.entry.get("iso2"),
                "name": self.name,
                "sub_region": self.sub_region,
            },
            "currency": {
                "code": cur["code"],
                "symbol": cur.get("symbol") or cur["code"],
                "per_usd": cur["per_usd"],
                "year": cur.get("year"),
                "source": cur.get("source"),
            },
            "fallback": self.fallback,
            "notes": [],
        }
        if crop_ids:
            prices = []
            for cid in dict.fromkeys(c for c in crop_ids if c):
                if not _crop(cid):
                    continue
                p = self.price(cid)
                co = self.cost(cid)
                ny = ((self.entry or {}).get("yields") or {}).get(cid)
                prices.append(
                    {
                        "crop": cid,
                        "national_yield_t_ha": round(float(ny["t_ha"]), 2) if ny else None,
                        "national_yield_years": ny.get("years") if ny else None,
                        "price_usd_t": round(p["usd_t"], 1),
                        "price_local_t": round(self.local(p["usd_t"]), 1),
                        "price_scope": p["scope"],
                        "price_years": p.get("years"),
                        "price_source": p["source"],
                        "cost_usd_ha": round(co["usd_ha"]),
                        "cost_local_ha": round(self.local(co["usd_ha"])),
                        "cost_scope": co["scope"],
                    }
                )
            out["crops"] = prices
            if any(p["price_scope"] != "country" for p in prices):
                out["notes"].append(
                    "Crops without a national FAOSTAT producer price use the sub-region or world median, or the reference "
                    "price scaled by this country's farm-price index (see price_scope)."
                )
        out["nitrogen"] = self.n_price()
        from .yieldcal import country_factors

        yf = country_factors().get(self.iso3 or "") if self.iso3 else None
        out["yield_calibration"] = {
            "country_factor": float(yf["factor"]) if yf else 1.0,
            "method": (
                "IA yield benchmark residual for this country (V10)"
                if yf and yf.get("method") == "benchmark"
                else "FAOSTAT national yields relative to the macro region (half weight)"
                if yf
                else "no country factor (macro-region calibration only)"
            ),
            "n": int(yf["n"]) if yf else 0,
        }
        out["cost_method"] = (
            "Production costs: reference enterprise budget × this country's FAOSTAT yield level (input intensity) × "
            "World Bank price level for the non-traded share (labour, services, land)."
        )
        if self.fallback:
            out["notes"].append(
                "The field's country could not be determined (at sea or outside the country grid): crop-table reference "
                "prices and costs in USD are used."
            )
        out["sources"] = data().get("sources", {})
        return out


@lru_cache(maxsize=512)
def econ_for_country(iso3: str | None) -> Econ:
    e = data()["countries"].get(iso3 or "", {}) if iso3 else {}
    return Econ(iso3 if e else None, e)


def econ_for(lat: float, lon: float) -> Econ:
    return econ_for_country(country_of(lat, lon))


REFERENCE = Econ(None, {})
